"""Deterministic report rendering, with no model-authored claims or numbers."""
from .agent_facts import model_money_view


def report_html(web,ledger,calls):
    from .agent_tasks import answer
    from .agent_web import _sources_html
    esc=web.esc;remaining=[600];cut=[False]
    def show(value,depth=0):
        if remaining[0]<=0 or depth>9:
            cut[0]=True;return '<p>More records are available in the full tool result.</p>'
        remaining[0]-=1
        if isinstance(value,dict):
            parts=[]
            for k,v in value.items():
                if remaining[0]<=0:cut[0]=True;break
                label=str(k).removesuffix('_display').replace('_',' ').capitalize()
                if str(k).endswith('_minor'):label+=' (integer minor units; currency not inferred)'
                if isinstance(v,(dict,list)):
                    parts.append('<details><summary>'+esc(label)+'</summary>'+show(v,depth+1)+'</details>')
                else:parts.append('<div class="kv"><span>'+esc(label)+'</span><b>'+show(v,depth+1)+'</b></div>')
            return ''.join(parts) or '<p>No recorded entries.</p>'
        if isinstance(value,list):
            if len(value)>50:cut[0]=True
            return ''.join('<section class="card">'+show(v,depth+1)+'</section>' for v in value[:50]) or '<p>No recorded entries.</p>'
        if value is None:return 'Not recorded / not applicable'
        if isinstance(value,bool):return 'Yes' if value else 'No'
        return esc(str(value))
    body='<section class="card" data-guided-answer><h2>Computed answer</h2><p>Generated by local code from the selected task and recorded inputs. No model financial commentary.</p>'
    body+='<ul>'+''.join('<li>'+esc(s)+'</li>' for s in answer(calls).splitlines())+'</ul></section>'
    body+=_sources_html(web,[c for c in calls if isinstance(c.get('result'),dict)])
    for call in calls:
        if not call.get('ok'):continue
        result=call['result']
        if call['name']=='get_evidence':
            # Exact settlement/loan rows are rendered above; expose other named
            # reports separately without losing them behind a huge evidence list.
            result={k:v for k,v in result.items() if k not in {'financial_review','evidence'}}
        display=model_money_view(result,ledger)
        body+='<section class="card" data-guided-facts><h2>Recorded report details</h2><p>Money display values carry their currency. Missing data is not zero. Evidence references do not authenticate a source.</p>'+show(display)+'</section>'
    if cut[0]:body+='<p class="warn">Display shortened. Inspect the full deterministic tool result or the dedicated report page for remaining records. No omitted value is assumed zero.</p>'
    return body
